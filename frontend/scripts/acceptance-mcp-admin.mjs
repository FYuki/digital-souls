// 実Core・実HTTP/stdio MCPへ接続し、通信を置換せず管理画面を受け入れる。
import { chromium, expect as baseExpect } from '@playwright/test'
import { readFileSync } from 'node:fs'
const expect = baseExpect.configure({ timeout: 35000 })
const [configPath, phase] = process.argv.slice(2)
const config = JSON.parse(readFileSync(configPath, 'utf8'))
const passed = (check) => console.log('MCP_ADMIN_ACCEPTANCE ' + JSON.stringify({ check, status: 'passed' }))
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 980 } })
  page.setDefaultTimeout(35000)
  await page.goto(config.frontend)
  await page.getByRole('button', { name: /Addon \/ 連携/ }).click()
  const back = () => page.getByRole('button', { name: '一覧へ戻る' }).click()
  const row = (name) => page.getByRole('list', { name: '登録済みの連携' }).getByRole('listitem').filter({ has: page.getByRole('heading', { name, exact: true }) })
  async function add(name, endpoint, bearer = false) {
    await page.getByRole('button', { name: '外部MCPを追加', exact: true }).click()
    await page.getByLabel('表示名', { exact: true }).fill(name)
    await page.getByLabel('接続先URL').fill(endpoint)
    if (bearer) {
      await page.getByLabel('認証', { exact: true }).selectOption('bearer')
      await page.getByLabel('APIキー', { exact: true }).fill('synthetic-test-token')
    }
    await page.getByRole('button', { name: '登録して接続確認' }).click()
    await expect(page.getByText(/設定を保存しました/)).toBeVisible()
    await expect(page.getByText('利用意思: OFF / 無効')).toBeVisible()
  }
  async function remove(name) {
    await row(name).getByRole('button', { name: `${name}の詳細・編集` }).click()
    await page.getByRole('button', { name: '接続を削除…' }).click()
    await page.getByRole('button', { name: '接続とcredentialを削除' }).click()
    await expect(page.getByRole('button', { name: '外部MCPを追加', exact: true })).toBeVisible()
    await page.getByRole('button', { name: '状態を再取得' }).click()
    await expect(row(name)).toHaveCount(0)
  }
  if (phase === 'initial') {
    await add('HTTP接続', config.http)
    await expect(page.getByText('接続確認済み', { exact: true })).toBeVisible()
    await expect(page.getByText('Tool 6件 / Resource 1件 / Prompt 1件')).toBeVisible()
    await back()
    await row('HTTP接続').getByRole('switch').click()
    await expect(row('HTTP接続').getByText('使用可能', { exact: true })).toBeVisible()
    passed('http-register-off-enable')
    await row('HTTP接続').getByRole('button', { name: 'HTTP接続の詳細・編集' }).click()
    await page.getByLabel('表示名', { exact: true }).fill('HTTP接続編集')
    await page.getByRole('button', { name: '設定を保存', exact: true }).click()
    await expect(page.getByText('設定を保存しました。')).toBeVisible()
    await expect(page.getByText('利用意思: ON / 使用可能')).toBeVisible()
    await back()
    passed('display-name-edit-keeps-confirmed')
    for (const name of ['Bearer接続', 'Bearer複製']) {
      await add(name, config.bearer, true)
      await expect(page.getByText('接続確認済み', { exact: true })).toBeVisible()
      await expect(page.getByLabel('新しいAPIキー（更新する場合のみ）')).toHaveValue('')
      await expect(page.getByRole('switch')).toHaveCount(0)
      await back()
    }
    await remove('Bearer接続')
    await row('Bearer複製').getByRole('button', { name: 'Bearer複製の詳細・編集' }).click()
    await page.getByRole('button', { name: '接続テスト' }).click()
    await expect(page.getByText('接続を確認しました。')).toBeVisible()
    await page.getByLabel('新しいAPIキー（更新する場合のみ）').fill('synthetic-wrong-token')
    await page.getByRole('button', { name: '設定を保存', exact: true }).click()
    await expect(page.getByText('接続未確認（前回確認失敗）', { exact: true })).toBeVisible()
    await page.getByLabel('新しいAPIキー（更新する場合のみ）').fill('synthetic-test-token')
    await page.getByRole('button', { name: '設定を保存', exact: true }).click()
    await expect(page.getByText('接続確認済み', { exact: true })).toBeVisible()
    await back()
    passed('bearer-duplicate-isolation-and-rotation')
    await page.getByRole('button', { name: '外部MCPを追加', exact: true }).click()
    await page.getByLabel('表示名', { exact: true }).fill('stdio接続')
    await page.getByLabel('接続方式').selectOption('stdio')
    await page.getByLabel('実行ファイル').fill(config.python)
    await page.getByRole('button', { name: '引数を追加' }).click()
    await page.getByRole('textbox', { name: '引数 1', exact: true }).fill(config.server)
    await page.getByRole('button', { name: '登録して接続確認' }).click()
    await expect(page.getByText('接続確認済み', { exact: true })).toBeVisible()
    await expect(page.getByText('Tool 6件 / Resource 1件 / Prompt 1件')).toBeVisible()
    await back()
    passed('stdio-register-discovery')
    await add('接続未確認の登録', config.unreachable)
    await expect(page.getByText('接続未確認（前回確認失敗）', { exact: true })).toBeVisible()
    await back()
    await row('接続未確認の登録').getByRole('switch').click()
    await expect(row('接続未確認の登録').getByRole('alert')).toHaveText('接続を確認できなかったため、ONにできませんでした。')
    await expect(row('接続未確認の登録').getByRole('switch')).toHaveAttribute('aria-checked', 'false')
    passed('failed-save-and-enable-remain-off')
    await add('Toolなし接続', config.empty)
    await expect(page.getByText('接続確認済み', { exact: true })).toBeVisible()
    await expect(page.getByText('取得したToolは0件です。')).toBeVisible()
    await back()
    await expect(page.getByRole('list', { name: '登録済みの連携' }).getByRole('listitem')).toHaveCount(5)
    await page.screenshot({ path: config.screenshot, fullPage: true })
    await page.setViewportSize({ width: 320, height: 900 })
    await expect(row('stdio接続').getByRole('button', { name: 'stdio接続の詳細・編集' })).toBeVisible()
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), { timeout: 35000 }).toBe(true)
    passed('zero-tools-and-responsive-list')
  } else if (phase === 'restored') {
    await expect(page.getByRole('list', { name: '登録済みの連携' }).getByRole('listitem')).toHaveCount(5)
    await expect(row('HTTP接続編集').getByText('使用可能', { exact: true })).toBeVisible()
    await expect(row('HTTP接続編集').getByRole('switch')).toHaveAttribute('aria-checked', 'true')
    await expect(row('stdio接続').getByRole('switch')).toHaveAttribute('aria-checked', 'false')
    await expect(row('stdio接続').getByText('接続確認済み', { exact: true })).toBeVisible()
    await row('Bearer複製').getByRole('button', { name: 'Bearer複製の詳細・編集' }).click()
    await expect(page.getByText('credential: 設定済み', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: '接続テスト' }).click()
    await expect(page.getByText('接続を確認しました。')).toBeVisible()
    passed('restart-restores-settings-intent-history-and-credential')
  } else if (phase === 'disconnected') {
    await row('HTTP接続編集').getByRole('button', { name: 'HTTP接続編集の詳細・編集' }).click()
    await page.getByRole('button', { name: '接続テスト' }).click()
    await expect(page.getByText('接続確認に失敗しました。')).toBeVisible()
    await expect(page.getByText('接続不可', { exact: true })).toBeVisible()
    await expect(page.getByText(/^利用意思: ON/)).toBeVisible()
    await expect(page.getByText(/^最終成功:/)).toBeVisible()
    await page.getByLabel('接続先URL').fill(config.unreachable)
    await page.getByRole('button', { name: '設定を保存', exact: true }).click()
    await expect(page.getByText('接続未確認（前回確認失敗）', { exact: true })).toBeVisible()
    await expect(page.getByText(/^利用意思: ON/)).toBeVisible()
    await back()
    passed('disconnect-and-settings-change-keep-on-intent')
    for (const name of ['HTTP接続編集', 'Bearer複製', 'stdio接続', '接続未確認の登録', 'Toolなし接続']) await remove(name)
    await expect(page.getByText('登録済みの連携はありません')).toBeVisible()
    passed('delete-all-connections-and-owned-credentials')
  } else throw new Error('unknown acceptance phase')
} finally { await browser.close() }
